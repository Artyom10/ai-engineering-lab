"""Minimal agent loop on the Messages API (exercise 01 / AI-5).

The whole point of this file: the Messages API is a single stateless HTTP call.
"Agentic" behaviour exists only because *our code* calls it again, carrying the
conversation plus the results of the tools the model asked for.

Who decides what:
  model -> whether a tool is needed, which one, with what arguments, and whether
           the task is finished (reported through `stop_reason`)
  code  -> whether to really execute the call, what the result is, and whether to
           send another request at all

Run:
    python exercises/01-agent-loop/main.py
    python exercises/01-agent-loop/main.py "your question"
"""

from __future__ import annotations

import ast
import json
import operator
import os
import sys

import anthropic
from dotenv import load_dotenv

# Cheapest model that is sufficient here: this exercise is about the loop,
# not about reasoning quality (see CLAUDE.md).
MODEL = "claude-haiku-5-5"

# Safety bound only. The loop is supposed to end because the model said so
# (`stop_reason == "end_turn"`), never because this number was reached.
# Hitting it is a bug or a runaway agent, not a normal exit.
MAX_ITERATIONS = 20

# Generous enough that adaptive thinking + a short answer never truncate.
MAX_TOKENS = 4096


# ---------------------------------------------------------------------------
# Tool 1: calculator
# ---------------------------------------------------------------------------

class ToolError(Exception):
    """A tool failed in a way the model should hear about, not a crash."""


# Only these node types and operators are allowed through. Everything else in
# the expression is rejected before any evaluation happens.
_BIN_OPS = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.Mod: operator.mod,
    ast.Pow: operator.pow,
}
_UNARY_OPS = {ast.UAdd: operator.pos, ast.USub: operator.neg}

# Guard against expressions that are valid arithmetic but hang the process,
# e.g. 9 ** 9 ** 9.
_MAX_EXPONENT = 64


def _eval_node(node: ast.AST) -> float:
    if isinstance(node, ast.Constant):
        if isinstance(node.value, bool) or not isinstance(node.value, (int, float)):
            raise ToolError(f"unsupported constant: {node.value!r}")
        return node.value

    if isinstance(node, ast.UnaryOp) and type(node.op) in _UNARY_OPS:
        return _UNARY_OPS[type(node.op)](_eval_node(node.operand))

    if isinstance(node, ast.BinOp) and type(node.op) in _BIN_OPS:
        left = _eval_node(node.left)
        right = _eval_node(node.right)
        if isinstance(node.op, ast.Pow) and abs(right) > _MAX_EXPONENT:
            raise ToolError(f"exponent too large (max {_MAX_EXPONENT})")
        if isinstance(node.op, (ast.Div, ast.Mod)) and right == 0:
            raise ToolError("division by zero")
        return _BIN_OPS[type(node.op)](left, right)

    raise ToolError(f"unsupported syntax: {type(node).__name__}")


def calculate(expression: str) -> str:
    """Evaluate an arithmetic expression without eval().

    `expression` is text generated by an LLM, which in turn saw text written by a
    user: it is untrusted input. `eval()` here would mean arbitrary code
    execution driven by a prompt.
    """
    # Strip separators models like to emit: 1,230 / 184_500_000.
    cleaned = expression.replace(",", "").replace("_", "")
    try:
        tree = ast.parse(cleaned, mode="eval")
    except SyntaxError as exc:
        raise ToolError(f"could not parse expression: {exc.msg}") from exc

    result = _eval_node(tree.body)
    return json.dumps({"expression": expression, "result": result})


# ---------------------------------------------------------------------------
# Tool 2: web search stub
# ---------------------------------------------------------------------------
# A stub on purpose. Its job in this exercise is to hold facts the model cannot
# know in advance, which is what forces *sequential* tool calls: the model must
# receive the search result before it can compute anything with it.

_SEARCH_INDEX = {
    "acme corp annual revenue 2026": (
        "Acme Corp reported annual revenue of 184500000 USD for fiscal year 2026."
    ),
    "acme corp number of employees headcount": (
        "Acme Corp had 1230 employees at the end of 2026."
    ),
    "acme corp founded headquarters": (
        "Acme Corp was founded in 1994 and is headquartered in Lisbon, Portugal."
    ),
}


def web_search(query: str) -> str:
    """Look the query up in the canned index by naive keyword overlap."""
    words = {w.strip(".,?!").lower() for w in query.split()}

    best_score, best_doc = 0, None
    for key, doc in _SEARCH_INDEX.items():
        score = len(words & set(key.split()))
        if score > best_score:
            best_score, best_doc = score, doc

    if best_doc is None:
        # NOT an error: the search ran fine and found nothing. Returning this as
        # an error would invite a pointless retry (exercise 03 goes deeper).
        return json.dumps({"query": query, "result_count": 0, "results": []})

    return json.dumps({"query": query, "result_count": 1, "results": [best_doc]})


# ---------------------------------------------------------------------------
# Tool schemas: the only thing the model ever sees about our tools
# ---------------------------------------------------------------------------

TOOLS = [
    {
        "name": "calculate",
        "description": (
            "Evaluate an arithmetic expression and return the exact result. "
            "Supports + - * / % ** and parentheses over plain numbers. "
            "Example input: '184500000 / 1230'. "
            "Do NOT pass variable names, units or currency symbols — numbers only."
        ),
        "input_schema": {
            "type": "object",
            "properties": {
                "expression": {
                    "type": "string",
                    "description": "Arithmetic expression, e.g. '(17 * 23 + 4) / 5'.",
                }
            },
            "required": ["expression"],
        },
    },
    {
        "name": "web_search",
        "description": (
            "Search an internal company knowledge base for facts such as revenue, "
            "headcount or founding details. Returns short text snippets. "
            "Use it for any figure you do not already have; never guess the numbers."
        ),
        "input_schema": {
            "type": "object",
            "properties": {
                "query": {
                    "type": "string",
                    "description": "Keyword search query, e.g. 'Acme Corp revenue 2026'.",
                }
            },
            "required": ["query"],
        },
    },
]

TOOL_REGISTRY = {"calculate": calculate, "web_search": web_search}


def execute_tool(name: str, tool_input: dict) -> tuple[str, bool]:
    """Run one tool call. Returns (content_for_the_model, is_error).

    Errors are turned into tool results, not exceptions: the model can read an
    error and correct itself, but it cannot read a traceback from a dead process.
    """
    func = TOOL_REGISTRY.get(name)
    if func is None:
        # The model hallucinated a tool name. Tell it, instead of crashing.
        return f"Error: unknown tool {name!r}. Available: {sorted(TOOL_REGISTRY)}", True

    try:
        return func(**tool_input), False
    except ToolError as exc:
        return f"Error: {exc}", True
    except TypeError as exc:
        # Wrong/missing arguments in the model-generated input.
        return f"Error: invalid arguments for {name}: {exc}", True


# ---------------------------------------------------------------------------
# Trace helpers
# ---------------------------------------------------------------------------

def _truncate(text: str, limit: int = 160) -> str:
    text = text.replace("\n", " ")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _print_turn(iteration: int, response: anthropic.types.Message) -> None:
    usage = response.usage
    print(
        f"\n--- turn {iteration} | stop_reason={response.stop_reason} "
        f"| in={usage.input_tokens} out={usage.output_tokens} tokens"
    )
    for block in response.content:
        if block.type == "text" and block.text.strip():
            print(f"  model says : {_truncate(block.text)}")
        elif block.type == "tool_use":
            print(f"  wants tool : {block.name}({json.dumps(block.input)})  id={block.id}")


# ---------------------------------------------------------------------------
# The loop
# ---------------------------------------------------------------------------

def run_agent(question: str, client: anthropic.Anthropic) -> str | None:
    """Drive the conversation until the model says it is done."""
    messages: list[dict] = [{"role": "user", "content": question}]

    for iteration in range(1, MAX_ITERATIONS + 1):
        response = client.messages.create(
            model=MODEL,
            max_tokens=MAX_TOKENS,
            tools=TOOLS,
            messages=messages,
        )
        _print_turn(iteration, response)

        # `stop_reason` is the protocol-level signal and the only reliable one.
        # Never decide "it sounds finished" by parsing the model's prose.
        if response.stop_reason != "tool_use":
            if response.stop_reason == "max_tokens":
                print("  ! truncated: raise MAX_TOKENS")
            elif response.stop_reason == "refusal":
                print(f"  ! refused: {response.stop_details}")
            return next(
                (b.text for b in response.content if b.type == "text"), None
            )

        # Append the assistant turn *verbatim* (`response.content`, not just the
        # text): the tool_use blocks — and any thinking blocks — must come back
        # exactly as the API produced them.
        messages.append({"role": "assistant", "content": response.content})

        # One response can contain several tool_use blocks (parallel calls).
        # All their results must go back in a SINGLE user message, each matched
        # to its request by tool_use_id.
        tool_results = []
        for block in response.content:
            if block.type != "tool_use":
                continue
            content, is_error = execute_tool(block.name, block.input)
            marker = "ERROR" if is_error else "ok"
            print(f"  tool result: [{marker}] {_truncate(content)}")
            tool_results.append(
                {
                    "type": "tool_result",
                    "tool_use_id": block.id,
                    "content": content,
                    "is_error": is_error,
                }
            )

        messages.append({"role": "user", "content": tool_results})

    # Only reachable if the model kept asking for tools MAX_ITERATIONS times.
    print(
        f"\n! stopped after {MAX_ITERATIONS} iterations without end_turn — "
        "this is a failure, not a result"
    )
    return None


def main() -> int:
    load_dotenv()
    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("ANTHROPIC_API_KEY is not set (see .env.example)", file=sys.stderr)
        return 1

    question = " ".join(sys.argv[1:]) or (
        "What was Acme Corp's 2026 revenue per employee? "
        "Look up both figures, then compute it."
    )
    print(f"question: {question}")

    answer = run_agent(question, anthropic.Anthropic())
    print(f"\n=== final answer ===\n{answer}")
    return 0 if answer else 1


if __name__ == "__main__":
    sys.exit(main())
